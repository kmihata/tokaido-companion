import type { Dataset } from '../data/load';
import type { Day, Station } from '../data/schemas';
import type { DayLeg } from './dayPlan';
import type { PlanningLine } from './planningLine';
import { nearestPointOnLine } from './geo';
import type { Position } from './geo';

/**
 * How far outside a day's own stretch a post station can sit and still be part
 * of that day.
 *
 * Not zero, because a day usually stops at a bed rather than at a post town.
 * Walk 4 finishes on the Moto-Hakone lake shore 1.2 km short of Hakone-juku;
 * Walk 13 stops at Ono-cho, 2.1 km short of Seki-juku. Those stations are the
 * day's business even though the line stops before them.
 *
 * Three kilometres, because the measurements fall into two clean groups with
 * nothing in between. Stations a day stops just short of or starts just past:
 * 1.17, 1.20, 1.53, 2.11, 2.72 km. Stations belonging to the neighbouring
 * day: 7.34, 8.52, 9.77, 10.72, 14.79, 15.81, 16.02 km. The gap runs from 2.72
 * to 7.34 and the threshold sits in it.
 */
export const STATION_REACH_KM = 3;

/**
 * The post stations that belong to a day — the single list the card's station
 * section and its Hiroshige prints are both built from.
 *
 * WHY they are computed rather than read from `day.stationIds`:
 *
 * The two used to come from different places. Stations were the hand-kept
 * `stationIds`; prints were generated by projecting stations onto a line made
 * from the concatenated BASE paths and cutting at a running sum of
 * `nominalDistanceKm`. Those are two rulers — 518.53 km against the active
 * route's 537.84 km — and nineteen kilometres of drift accumulate between
 * them. On 2026-10-16 Walk 4 listed stations 9, 10 and 11 and showed no prints
 * at all, while Walk 5 showed Hakone's. Kevin found it on the phone.
 *
 * `stationIds` is kept, and still says something true, but it is not a list of
 * what a day walks past: by the file's own convention a day also names the
 * station it came from and the one it is heading toward, which on Walk 4 means
 * Mishima, sixteen kilometres and a mountain away. Kevin's call on 2026-10-17
 * was to show what is on the day. So this measures, on the planning line that
 * every other distance in the app uses, and the card shows one list.
 */
export function stationsForDay(
  dataset: Dataset,
  day: Day,
  leg: DayLeg | null,
  line: PlanningLine | null,
): Station[] {
  if (!leg || !line || line.positions.length < 2) {
    // No geometry to ask. Fall back to what the day names rather than showing
    // an empty section on a card that should be readable with no network and
    // no plan loaded.
    const byId = new Map(dataset.stations.map((s) => [s.id, s]));
    return day.stationIds.map((id) => byId.get(id)).filter((s): s is Station => Boolean(s));
  }

  const km = stationKm(dataset, line);
  const lo = leg.startAlongKm - STATION_REACH_KM;
  const hi = leg.plan.endAlongKm + STATION_REACH_KM;

  return dataset.stations
    .filter((s) => {
      const at = km.get(s.id);
      return at !== undefined && at >= lo && at <= hi;
    })
    .sort((a, b) => (km.get(a.id) ?? 0) - (km.get(b.id) ?? 0));
}

/** The prints for those stations, in the same order. */
export function hiroshigeForStations(
  dataset: Dataset,
  stations: readonly Station[],
  day: Day,
): string[] {
  const printFor = new Map<string, string>();
  for (const h of dataset.hiroshige) {
    if (h.stationId) printFor.set(h.stationId, h.id);
  }
  const ids = stations.map((s) => printFor.get(s.id)).filter((id): id is string => Boolean(id));
  // A card that lists a station must show its print, and vice versa — that
  // disagreement is the whole reason this module exists. With no stations
  // resolved there is nothing to be consistent with, so fall back.
  return ids.length > 0 ? [...new Set(ids)] : [...day.hiroshigeRefIds];
}

/**
 * Station positions along the planning line, computed once per line.
 *
 * Fifty-five stations against ten thousand points is half a million segment
 * projections; doing that on every render of a day card would be felt on a
 * phone. The line object is rebuilt whenever the route or an edit changes, so
 * keying the cache on it invalidates at exactly the right moment.
 */
const kmCache = new WeakMap<PlanningLine, Map<string, number>>();

function stationKm(dataset: Dataset, line: PlanningLine): Map<string, number> {
  const hit = kmCache.get(line);
  if (hit) return hit;
  const km = new Map<string, number>();
  for (const s of dataset.stations) {
    const near = nearestPointOnLine(line.positions, [s.lon, s.lat] as Position);
    if (near) km.set(s.id, near.alongKm);
  }
  kmCache.set(line, km);
  return km;
}
